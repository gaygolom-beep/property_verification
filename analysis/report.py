"""
Verification report generation (Module 11) using reportlab.
Produces a one-page-plus PDF: property summary, risk score/level, every
finding from the analysis run, and a human-review sign-off block.
"""
import io

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable,
)

INK = colors.HexColor("#101e2b")
PRIMARY = colors.HexColor("#146356")
GOLD = colors.HexColor("#b8863a")
BRICK = colors.HexColor("#a8453c")
SLATE = colors.HexColor("#3b6e91")
MUTED = colors.HexColor("#5c6b74")
BORDER = colors.HexColor("#e0e5e7")

LEVEL_COLOR = {"Low": PRIMARY, "Medium": SLATE, "High": BRICK}
SEVERITY_LABEL = {"pass": "PASS", "info": "INFO", "medium": "FLAG", "high": "FLAG"}
SEVERITY_COLOR = {"pass": PRIMARY, "info": MUTED, "medium": GOLD, "high": BRICK}


def build_report_pdf(prop, analysis):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        topMargin=18 * mm, bottomMargin=18 * mm, leftMargin=18 * mm, rightMargin=18 * mm,
        title=f"Verification Report - {prop.title}",
    )
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Heading1"], textColor=INK, fontSize=18, spaceAfter=2)
    eyebrow = ParagraphStyle("eyebrow", parent=styles["Normal"], textColor=GOLD, fontSize=9,
                              spaceAfter=10, fontName="Helvetica-Bold")
    label = ParagraphStyle("label", parent=styles["Normal"], textColor=MUTED, fontSize=8.5, fontName="Helvetica-Bold")
    body = ParagraphStyle("body", parent=styles["Normal"], textColor=INK, fontSize=10, leading=14)
    small = ParagraphStyle("small", parent=styles["Normal"], textColor=MUTED, fontSize=8.5, leading=12)

    story = []
    story.append(Paragraph("PROPVERIFY &nbsp;&middot;&nbsp; VERIFICATION REPORT", eyebrow))
    story.append(Paragraph(prop.title, h1))
    story.append(Paragraph(prop.full_address, small))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", color=BORDER, thickness=1))
    story.append(Spacer(1, 10))

    details = [
        ["Property Type", prop.property_type, "Survey / Plot No.", prop.survey_number or "—"],
        ["Area", f"{prop.area_sq_ft:g} sq. ft." if prop.area_sq_ft else "—", "Owner", prop.owner.full_name],
        ["Current Status", prop.overall_status, "Report Generated", analysis.created_at.strftime("%d %b %Y, %I:%M %p")],
    ]
    t = Table(details, colWidths=[38 * mm, 52 * mm, 38 * mm, 52 * mm])
    t.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"), ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9), ("TEXTCOLOR", (0, 0), (0, -1), MUTED), ("TEXTCOLOR", (2, 0), (2, -1), MUTED),
        ("TEXTCOLOR", (1, 0), (1, -1), INK), ("TEXTCOLOR", (3, 0), (3, -1), INK),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6), ("TOPPADDING", (0, 0), (-1, -1), 2),
    ]))
    story.append(t)
    story.append(Spacer(1, 16))

    level_color = LEVEL_COLOR.get(analysis.risk_level, MUTED)
    score_style = ParagraphStyle("score", parent=styles["Normal"], textColor=level_color, fontSize=22, fontName="Helvetica-Bold", leading=26)
    story.append(Paragraph(f"{analysis.risk_score}/100 &nbsp; {analysis.risk_level} Risk", score_style))
    story.append(Spacer(1, 10))
    story.append(Paragraph(
        f"Automated checks: {analysis.checks_passed} of {analysis.checks_run} passed. "
        f"This score is generated by pattern-based document matching (OCR + rule-based comparison), "
        f"not a legal determination — a human verification officer must confirm the final outcome.",
        small))
    story.append(Spacer(1, 14))
    story.append(Paragraph("FINDINGS", eyebrow))

    rows = [["", "Finding", "Detail"]]
    row_colors = []
    for f in analysis.findings:
        rows.append([SEVERITY_LABEL.get(f["severity"], ""), f["title"], f["detail"]])
        row_colors.append(SEVERITY_COLOR.get(f["severity"], MUTED))

    table_data = [rows[0]] + [
        [Paragraph(r[0], ParagraphStyle("s", fontSize=8, fontName="Helvetica-Bold", textColor=row_colors[i])),
         Paragraph(r[1], ParagraphStyle("t", fontSize=9, fontName="Helvetica-Bold", textColor=INK)),
         Paragraph(r[2], ParagraphStyle("d", fontSize=8.5, textColor=MUTED, leading=11))]
        for i, r in enumerate(rows[1:])
    ]
    ft = Table(table_data, colWidths=[16 * mm, 45 * mm, 119 * mm], repeatRows=1)
    ft.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef1f2")),
        ("FONTSIZE", (0, 0), (-1, 0), 8), ("TEXTCOLOR", (0, 0), (-1, 0), MUTED),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(ft)
    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", color=BORDER, thickness=1))
    story.append(Spacer(1, 10))
    story.append(Paragraph("HUMAN REVIEW SIGN-OFF", eyebrow))
    story.append(Paragraph(
        "Reviewing officer: ______________________________ &nbsp;&nbsp;&nbsp; "
        "Decision: &#9633; Verified &nbsp; &#9633; Rejected &nbsp; &#9633; Needs more documents "
        "&nbsp;&nbsp;&nbsp; Date: ______________", body))
    story.append(Spacer(1, 6))
    story.append(Paragraph(
        "Scope note: this report supports technical/document-consistency verification only. "
        "It is not a legal certification of property ownership or title.", small))

    doc.build(story)
    buf.seek(0)
    return buf
